-- 1. Create Entries Table
CREATE TABLE IF NOT EXISTS public.entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building TEXT NOT NULL,
    floor TEXT NOT NULL,
    department TEXT NOT NULL,
    internal_phone TEXT NOT NULL DEFAULT '',
    external_phone TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Create Indexes for High Performance Search
CREATE INDEX IF NOT EXISTS idx_entries_building ON public.entries(building);
CREATE INDEX IF NOT EXISTS idx_entries_floor ON public.entries(floor);
CREATE INDEX IF NOT EXISTS idx_entries_department ON public.entries(department);
CREATE INDEX IF NOT EXISTS idx_entries_sort_order ON public.entries(sort_order);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.entries ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any
DROP POLICY IF EXISTS "Allow public read-only access" ON public.entries;
DROP POLICY IF EXISTS "Allow authenticated insert" ON public.entries;
DROP POLICY IF EXISTS "Allow authenticated update" ON public.entries;
DROP POLICY IF EXISTS "Allow authenticated delete" ON public.entries;

-- 4. Set Policies:
-- (A) ทุกคนสามารถค้นหาและดูเบอร์โทรศัพท์ได้โดยไม่ต้องล็อกอิน (Public Read)
CREATE POLICY "Allow public read-only access" 
ON public.entries 
FOR SELECT 
USING (true);

-- (B) เฉพาะผู้ใช้ที่ล็อกอิน (Admin/IT) เท่านั้นที่สามารถ เพิ่ม/แก้ไข/ลบ ข้อมูลได้
CREATE POLICY "Allow authenticated insert" 
ON public.entries 
FOR INSERT 
TO authenticated 
WITH CHECK (true);

CREATE POLICY "Allow authenticated update" 
ON public.entries 
FOR UPDATE 
TO authenticated 
USING (true)
WITH CHECK (true);

CREATE POLICY "Allow authenticated delete" 
ON public.entries 
FOR DELETE 
TO authenticated 
USING (true);

